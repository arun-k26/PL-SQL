/*
What is Trigger ?
    1. Triggers are PL/SQL blocks that executed before or after or certains specific event.
    2. Triggers are executed automatically by the database server.
    3. Triggers are defined on Tables, views, schemas, databases.
    4. Triggers are fired or executed based on how we declared them.
        1. When a DML (Insert, Update, Delete).
        2. When a DDL (Create, Alter, Drop).
        3. When some database applications occur like (LogOn, StartUp, ServerError).
    5. These all are called as Database Triggers.
    
Why do we Use Trigger ?
    1. Security                     2. Auditing
    3. Data Integrity               4. Table Logging
    5. Event Logging                6. Derived Data
    

Types of Trigger ?
    1. DML Trigger : Before Trigger, After Trigger, Instead of Trigger
    2. Compound Trigger
    3. Non-DML Trigger : DDL Event Trigger, Database Event Trigger

*/